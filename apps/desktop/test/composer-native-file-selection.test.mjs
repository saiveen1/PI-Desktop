import assert from "node:assert/strict";
import test from "node:test";
import { IPC_WHITELIST } from "@pi-desktop/shared/protocol";
import { COMPOSER_FILE_SELECTION_CHANNEL, createComposerFileSelector } from "../electron/composer-file-selection.ts";
import { consumeComposerPickerSelection, rememberComposerNativeFiles } from "../electron/main/composer-picker.ts";
import { importComposerBrowserFiles } from "../src/lib/composer-file-import.ts";

function bridge() {
  const paths = new WeakMap(), selected = [], transferred = [];
  const api = {
    getDroppedFilePath: file => paths.get(file) ?? null,
    selectComposerFiles: createComposerFileSelector(file => {
      if (!(file instanceof File)) throw new Error("not a File");
      return paths.get(file) ?? "";
    }, async paths => {
      selected.push(paths);
      return { ok: true, data: { token: rememberComposerNativeFiles(paths, 1) } };
    }),
    importFiles: async (_session, token) => ({ files: consumeComposerPickerSelection(token, 1).map(path => ({ path, name: path.split("/").at(-1), size: 67108865, kind: "file", localReference: "reference-id" })) }),
    pasteFiles: async (_session, files) => {
      transferred.push(files);
      return { files: files.map(file => ({ path: "/scratch/" + file.name, name: file.name, kind: "image", size: file.data.byteLength })) };
    },
  };
  return { api, selected, transferred, native(name) {
    const file = new File([], name);
    paths.set(file, "/selected/" + name);
    file.arrayBuffer = () => assert.fail("native bytes were read");
    return file;
  } };
}

test("mixed disk and generated inputs preserve order and only transfer generated bytes", async () => {
  const run = bridge();
  const first = run.native("large.bin"), last = run.native("small.txt");
  const screenshot = new File(["pixels"], "screenshot.png", { type: "image/png" });
  const { files } = await importComposerBrowserFiles("session", [first, screenshot, last], run.api);
  assert.deepEqual(files.map(file => file.name), ["large.bin", "screenshot.png", "small.txt"]);
  assert.equal(files[0].localReference, "reference-id");
  assert.equal(files[2].localReference, "reference-id");
  assert.equal(files[1].localReference, undefined);
  assert.deepEqual(run.selected, [["/selected/large.bin", "/selected/small.txt"]]);
  assert.equal(run.transferred.length, 1);
  assert.equal(new TextDecoder().decode(run.transferred[0][0].data), "pixels");
});

test("private native selection is not invokable through the generic renderer channel whitelist", () => {
  assert.equal(IPC_WHITELIST.has(COMPOSER_FILE_SELECTION_CHANNEL), false);
});

test("selector rejects raw paths, forged objects, generated Files and over-limit batches before registering", async () => {
  const run = bridge();
  for (const files of [["/forged/file"], [{ path: "/forged/file" }], [new File([], "generated")], [], Array(21).fill(run.native("file"))]) {
    await assert.rejects(run.api.selectComposerFiles(files));
  }
  assert.deepEqual(run.selected, []);
});

test("native selection tokens retain sender binding and one-shot semantics", async () => {
  const run = bridge();
  const token = await run.api.selectComposerFiles([run.native("file")]);
  assert.throws(() => consumeComposerPickerSelection(token, 2), /unavailable/);
  assert.throws(() => consumeComposerPickerSelection(token, 1), /unavailable/);
  const next = await run.api.selectComposerFiles([run.native("file")]);
  assert.deepEqual(consumeComposerPickerSelection(next, 1), ["/selected/file"]);
  assert.throws(() => consumeComposerPickerSelection(next, 1), /unavailable/);
});

test("invalid native metadata and oversized mixed selections are rejected", async () => {
  for (const paths of [null, [], ["relative"], ["/bad\0path"], [1], Array(21).fill("/file")]) {
    assert.throws(() => rememberComposerNativeFiles(paths, 1), /invalid/);
  }
  const run = bridge();
  await assert.rejects(importComposerBrowserFiles("session", Array(21).fill(run.native("file")), run.api), /too many/);
  assert.deepEqual(run.selected, []);
});

test("failed native registration never falls back to copying the original file", async () => {
  const run = bridge();
  run.api.selectComposerFiles = async () => { throw new Error("selection rejected"); };
  await assert.rejects(importComposerBrowserFiles("session", [run.native("file")], run.api), /selection rejected/);
  assert.deepEqual(run.transferred, []);
});
